import { chromium } from '@playwright/test';
const browser = await chromium.launch({headless:true,args:[process.env.COURAGE_QA_GPU === 'metal' ? '--use-angle=metal' : '--use-angle=swiftshader','--enable-webgl']});
const page = await browser.newPage({viewport:{width:1440,height:900}});
await page.goto('http://localhost:3000');
await page.waitForLoadState('networkidle');
await page.locator('.loading').waitFor({state:'detached'});
await page.screenshot({path:'../courage-os-room.png'});
await page.keyboard.press('Enter');
await page.waitForFunction(()=>document.querySelector('main')?.getAttribute('data-view')==='screen');
await page.waitForTimeout(300);
await page.screenshot({path:'../courage-os-screen.png'});
await page.mouse.click(220,530);
await page.waitForTimeout(300);
await page.screenshot({path:'../courage-os-lamp.png'});
await page.mouse.click(220,530);
await page.mouse.click(943,605);
await page.waitForTimeout(1000);
await page.screenshot({path:'../../work/powered-off.png'});
await page.mouse.click(943,605);
await browser.close();
