const paths = Object.fromEntries(
  Object.entries(glyphs).map(([char, data]) => [
    char,
    data
      .trim()
      .split("|")
      .map((path) =>
        path
          .trim()
          .split(/\s+/)
          .map((point) => point.split(",").map(Number)),
      ),
  ]),
);
export function lineWidth(text: string, size: number) {
  return Math.max(0, text.length * size * 1.2 - size * 0.15);
}
export function monoline(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  size: number,
  color: string,
) {
  ctx.save();
  ctx.lineCap = "round";
  ctx.lineJoin = "round";
  ctx.lineWidth = Math.max(0.8, size * 0.040);
  ctx.strokeStyle = color;
  ctx.shadowColor = color;
  ctx.shadowBlur = size * 0.13;
  ctx.setLineDash([]);
  const start = x - lineWidth(text, size) / 2;
  for (let i = 0; i < text.length; i++) {
    const char = text[i].toUpperCase();
    if (char === " ") continue;
    const strokes = paths[char] || paths["?"];
    ctx.beginPath();
    for (const stroke of strokes) {
      stroke.forEach(([px, py], j) => {
        const tx = start + i * size * 1.2 + px * size * 1.05,
          ty = y + (py - 0.5) * size;
        j ? ctx.lineTo(tx, ty) : ctx.moveTo(tx, ty);
      });
    }
    ctx.stroke();
  }
  ctx.restore();
}
